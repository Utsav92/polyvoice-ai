"use client";
import { useEffect, useRef, useState } from "react";
import { audioUrl, generate, getJob, getLanguages, getModels, getVoices, API, type Voice, type Job, type LangMatrix, type ModelInfo } from "@/lib/api";

const LANG_NAMES: Record<string, string> = {
  en: "English", hi: "Hindi", es: "Spanish", fr: "French", de: "German", ja: "Japanese",
  ar: "Arabic", ko: "Korean", pt: "Portuguese", it: "Italian",
};

export default function SpeechStudio() {
  const [models, setModels] = useState<ModelInfo[]>([]);
  const [modelId, setModelId] = useState("");
  const [voices, setVoices] = useState<Voice[]>([]);
  const [voiceId, setVoiceId] = useState("");
  const [matrix, setMatrix] = useState<LangMatrix>({});
  const [language, setLanguage] = useState("en");
  const [text, setText] = useState("Hello! This is speech generated by PolyVoice.");
  const [rate, setRate] = useState(1);
  const [format, setFormat] = useState<"wav" | "mp3">("wav");
  const [job, setJob] = useState<Job | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const [bars, setBars] = useState<number[]>([]);
  const abort = useRef(false);

  useEffect(() => {
    Promise.all([getModels(), getLanguages()]).then(([{ models }, { languages }]) => {
      setModels(models); setMatrix(languages);
      const m = models[0]; if (m) { setModelId(m.id); setLanguage(m.languages[0]); }
    }).catch((e) => setError(`Backend unreachable: ${e.message}`));
  }, []);

  const model = models.find((m) => m.id === modelId);
  useEffect(() => {
    if (!modelId) return;
    getVoices(language, modelId).then(({ voices }) => { setVoices(voices); setVoiceId(voices[0]?.id ?? ""); }).catch(() => setVoices([]));
  }, [language, modelId]);
  const voice = voices.find((v) => v.id === voiceId);

  async function run() {
    setBusy(true); setError(null); setJob(null); setBars([]); abort.current = false;
    try {
      const { job_id } = await generate({ text, language, model: modelId, voice_id: voiceId || undefined, speaking_rate: rate, format });
      let j = await getJob(job_id);
      while (!abort.current && (j.status === "queued" || j.status === "running")) {
        setJob(j); await new Promise((r) => setTimeout(r, 400)); j = await getJob(job_id);
      }
      setJob(j);
      if (j.status === "failed") setError(j.error);
      if (j.status === "succeeded" && j.audio_id) drawWave(j.audio_id);
    } catch (e) { setError((e as Error).message); } finally { setBusy(false); }
  }

  async function drawWave(id: string) {
    try {
      const buf = await (await fetch(audioUrl(id))).arrayBuffer();
      const ctx = new AudioContext();
      const data = (await ctx.decodeAudioData(buf)).getChannelData(0);
      const n = 120, step = Math.floor(data.length / n);
      setBars(Array.from({ length: n }, (_, i) => {
        let m = 0; for (let k = 0; k < step; k++) m = Math.max(m, Math.abs(data[i * step + k]));
        return m;
      }));
      ctx.close();
    } catch { /* waveform is cosmetic; playback still works */ }
  }

  const ready = job?.status === "succeeded" && job.audio_id;
  return (
    <main className="mx-auto max-w-4xl p-6 space-y-6">
      <header>
        <h1 className="text-2xl font-semibold tracking-tight">Speech Studio</h1>
        <p className="text-sm text-neutral-400">All audio is AI-generated and labeled as such.</p>
      </header>
      {error && <div role="alert" className="rounded border border-red-500/40 bg-red-500/10 p-3 text-sm text-red-300">{error}</div>}
      <textarea value={text} onChange={(e) => setText(e.target.value)} rows={6} maxLength={5000}
        className="w-full rounded-lg border border-neutral-700 bg-neutral-900 p-3 text-base" aria-label="Text to speak" />
      <div className="grid gap-4 sm:grid-cols-5">
        <label className="text-sm">Voice
          <select value={voiceId} onChange={(e) => setVoiceId(e.target.value)} disabled={voices.length === 0}
            className="mt-1 w-full rounded border border-neutral-700 bg-neutral-900 p-2">
            {voices.map((v) => <option key={v.id} value={v.id}>{v.name}</option>)}
          </select></label>
        <label className="text-sm">Model
          <select value={modelId} onChange={(e) => setModelId(e.target.value)}
            className="mt-1 w-full rounded border border-neutral-700 bg-neutral-900 p-2">
            {models.filter((m) => m.languages.includes(language)).map((m) => <option key={m.id} value={m.id} disabled={!!m.features.requires_reference || !m.available}>{m.name}{!m.available ? " (unavailable)" : m.features.requires_reference ? " (needs enrolled voice)" : ""}</option>)}
          </select></label>
        <label className="text-sm">Language
          <select value={language} onChange={(e) => { const l = e.target.value; setLanguage(l);
            const ok = matrix[l]?.models ?? []; if (!ok.includes(modelId)) setModelId(ok[0] ?? ""); }}
            className="mt-1 w-full rounded border border-neutral-700 bg-neutral-900 p-2">
            {Object.entries(matrix).map(([l, v]) => <option key={l} value={l} disabled={v.models.length === 0}>{LANG_NAMES[l] ?? l}{v.models.length === 0 ? " (unavailable)" : ""}</option>)}
          </select></label>
        <label className="text-sm">Speed {rate.toFixed(2)}×
          <input type="range" min={0.5} max={2} step={0.05} value={rate} disabled={!model?.features.speaking_rate}
            onChange={(e) => setRate(+e.target.value)} className="mt-3 w-full" /></label>
        <label className="text-sm">Format
          <select value={format} onChange={(e) => setFormat(e.target.value as "wav" | "mp3")}
            className="mt-1 w-full rounded border border-neutral-700 bg-neutral-900 p-2">
            <option value="wav">WAV</option><option value="mp3">MP3</option></select></label>
      </div>
      {voice?.sample_url && <div className="flex items-center gap-3 text-xs text-neutral-400">Voice sample <audio controls src={`${API}${voice.sample_url}`} className="h-8" /></div>}
      {voice && <p className="text-xs text-neutral-500">{voice.description} · {voice.license}</p>}
      {model && <p className="text-xs text-neutral-500">License: {model.license} · Commercial use: {model.commercial_use ? "yes" : "no"} ·
        Emotion control: {model.features.emotion ? "available" : "not supported by this model"}</p>}
      <button onClick={run} disabled={busy || !text.trim() || !modelId}
        className="rounded-lg bg-emerald-500 px-5 py-2 font-medium text-black disabled:opacity-40">
        {busy ? (job?.status ?? "submitting") + "…" : "Generate"}</button>
      {bars.length > 0 && (
        <div className="flex h-20 items-center gap-px" aria-hidden>
          {bars.map((b, i) => <div key={i} className="w-full rounded bg-emerald-400" style={{ height: `${Math.max(3, b * 100)}%` }} />)}
        </div>)}
      {ready && (
        <div className="space-y-2">
          <audio controls src={audioUrl(job.audio_id!)} className="w-full" />
          <a href={audioUrl(job.audio_id!)} download className="text-sm text-emerald-400 underline">Download {format.toUpperCase()}</a>
          {typeof job.metrics?.rtf === "number" && <p className="text-xs text-neutral-500">Measured RTF {(job.metrics.rtf as number).toFixed(2)} on {String(job.metrics.device)}</p>}
        </div>)}
    </main>
  );
}
